export function uiText(language: UiLanguage, text: string): string {
  if (language === "en") return text;
  return ZH_TEXT[text] ?? text;
}

export function uiValue(language: UiLanguage, value: string): string {
  if (language === "en") return value;
  if (ZH_TEXT[value]) return ZH_TEXT[value];
  if (/^INVALID_/.test(value)) return `无效：${value.replace(/^INVALID_/, "").replace(/_/g, " ")}`;
  return value;
}

export function uiNone(language: UiLanguage): string {
  return uiText(language, "None");
}

export function uiNumberSuffix(language: UiLanguage, suffix: string): string {
  if (language === "en") return suffix;
  if (suffix === " px") return " 像素";
  if (suffix === " px/°C") return " 像素/°C";
  return suffix;
}

export function uiObjectClass(language: UiLanguage, value: string): string {
  if (value === "A_BALLOON_ENVELOPE") return uiText(language, "A balloon envelope");
  if (value === "C_BUNDLE_ENVELOPE") return uiText(language, "C bundle envelope");
  if (value === "D_RESERVED_OBJECT") return uiText(language, "D reserved object");
  return uiValue(language, value);
}

export function uiDetector(language: UiLanguage, value: string): string {
  return uiValue(language, value);
}

export function uiDetectorMode(language: UiLanguage, value: string): string {
  if (value === "default" || value === "c_envelope_legacy") return uiText(language, "Original envelope detection");
  if (value === "contrast_widest_span") return uiText(language, "Contrast widest-span detection");
  return uiValue(language, value);
}

export function uiWidthMode(language: UiLanguage, value: string): string {
  return uiValue(language, value);
}

export function uiDatasetLabel(language: UiLanguage, dataset: { id: string; label?: string | null }): string {
  if (language === "zh" && dataset.label) return dataset.label;
  return dataset.id;
}

export function uiStatus(language: UiLanguage, status: string | null | undefined): string {
  if (!status) return uiNone(language);
  return uiValue(language, status);
}

export function readInitialUiLanguage(): UiLanguage {
  const saved = window.localStorage.getItem(UI_LANGUAGE_STORAGE_KEY);
  if (saved === "zh" || saved === "en") return saved;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}
